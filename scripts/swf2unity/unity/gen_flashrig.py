"""Generate Assets/Shaders/FlashRig.shader (the layer count makes the file too repetitive to keep by hand).

usage: python gen_flashrig.py [layers=128]
"""
import os
import sys

N = int(sys.argv[1]) if len(sys.argv) > 1 else 128
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "Assets", "Shaders", "FlashRig.shader")

HEADER = r'''// GENERATED by scripts/swf2unity/unity/gen_flashrig.py -- edit the generator, not this file.
//
// Draws one converted Flash piece (armor body part, weapon, pet) as a stack of up to %(n)d layers sampled from the
// sprite's own texture. Armors: the client composites every ItemSlots entry (with the player's colour-custom colours)
// into one runtime texture and gives each renderer Sprite.Create(thatTexture, baseRect); weapons and pets sample
// their own atlas. The quad covers the base rect; the shader ignores the base pixels and draws each layer image with
// its own affine transform, colour transform, image rect (flipbooks switch rects) and Flash blend mode, all of which
// an Animator on the GameObject animates per frame.
//   P = fragment position in texture pixels (y up), Q = A·P + T = position inside layer n's rect.
// Layers are sampled with explicit gradients only where they cover the fragment, so cost follows coverage.
Shader "SwordShine/FlashRig"
{
    Properties
    {
        [PerRendererData] _MainTex ("Sprite Texture", 2D) = "white" {}
        _AtlasSize ("Atlas size (px)", Vector) = (1024, 1024, 0, 0)
        _Tint ("Part tint (back limbs are black)", Vector) = (1, 1, 1, 1)
        _LayerCount ("Layer count", Float) = 0
        _MorphFrame ("Click-controlled parent frame", Float) = 0
        _CCEnabled ("RGB coefficient reconstruction", Float) = 0
        _CCDirectPalette ("Direct player palette", Float) = 0
        _CCSourceBase ("Base response source location", Float) = 5
        _CCSourceTrim ("Trim response source location", Float) = 1
        _CCSourceAccessory ("Accessory response source location", Float) = 2
        _CCExtraPalette ("Six location RGB reconstruction", Float) = 0
        _CCDirectSkin ("Direct skin response color", Color) = (0,0,0,1)
        _CCDirectHair ("Direct hair response color", Color) = (0,0,0,1)
        _CCDirectEye ("Direct eye response color", Color) = (0,0,0,1)
        _CCSkinTex ("Skin RGB slope", 2D) = "black" {}
        _CCHairTex ("Hair RGB slope", 2D) = "black" {}
        _CCEyeTex ("Eye RGB slope", 2D) = "black" {}
        _CCSkinHighTex ("Skin high RGB slope", 2D) = "black" {}
        _CCHairHighTex ("Hair high RGB slope", 2D) = "black" {}
        _CCEyeHighTex ("Eye high RGB slope", 2D) = "black" {}
        _CCSkinScale ("Skin coefficient scale", Vector) = (1,1,1,1)
        _CCSkinBias ("Skin coefficient bias", Vector) = (0,0,0,0)
        _CCHairScale ("Hair coefficient scale", Vector) = (1,1,1,1)
        _CCHairBias ("Hair coefficient bias", Vector) = (0,0,0,0)
        _CCEyeScale ("Eye coefficient scale", Vector) = (1,1,1,1)
        _CCEyeBias ("Eye coefficient bias", Vector) = (0,0,0,0)
        _CCSkinHighScale ("Skin high coefficient scale", Vector) = (1,1,1,1)
        _CCSkinHighBias ("Skin high coefficient bias", Vector) = (0,0,0,0)
        _CCHairHighScale ("Hair high coefficient scale", Vector) = (1,1,1,1)
        _CCHairHighBias ("Hair high coefficient bias", Vector) = (0,0,0,0)
        _CCEyeHighScale ("Eye high coefficient scale", Vector) = (1,1,1,1)
        _CCEyeHighBias ("Eye high coefficient bias", Vector) = (0,0,0,0)
        _CCDirectBase ("Direct base response color", Color) = (0,0,0,1)
        _CCDirectTrim ("Direct trim response color", Color) = (0,0,0,1)
        _CCDirectAccessory ("Direct accessory response color", Color) = (0,0,0,1)
        _CCKnot ("RGB response knot", Float) = 0.5019607843
        _CCConstantTex ("RGB constant and source alpha", 2D) = "black" {}
        _CCBaseTex ("Base RGB slope", 2D) = "black" {}
        _CCTrimTex ("Trim RGB slope", 2D) = "black" {}
        _CCAccessoryTex ("Accessory RGB slope", 2D) = "black" {}
        _CCBaseHighTex ("Base high RGB slope", 2D) = "black" {}
        _CCTrimHighTex ("Trim high RGB slope", 2D) = "black" {}
        _CCAccessoryHighTex ("Accessory high RGB slope", 2D) = "black" {}
        _CCConstantScale ("Constant decode scale", Vector) = (1,1,1,0)
        _CCConstantBias ("Constant decode bias", Vector) = (0,0,0,0)
        _CCBaseScale ("Base decode scale", Vector) = (1,1,1,0)
        _CCBaseBias ("Base decode bias", Vector) = (0,0,0,0)
        _CCTrimScale ("Trim decode scale", Vector) = (1,1,1,0)
        _CCTrimBias ("Trim decode bias", Vector) = (0,0,0,0)
        _CCAccessoryScale ("Accessory decode scale", Vector) = (1,1,1,0)
        _CCAccessoryBias ("Accessory decode bias", Vector) = (0,0,0,0)
        _CCBaseHighScale ("Base high decode scale", Vector) = (1,1,1,0)
        _CCBaseHighBias ("Base high decode bias", Vector) = (0,0,0,0)
        _CCTrimHighScale ("Trim high decode scale", Vector) = (1,1,1,0)
        _CCTrimHighBias ("Trim high decode bias", Vector) = (0,0,0,0)
        _CCAccessoryHighScale ("Accessory high decode scale", Vector) = (1,1,1,0)
        _CCAccessoryHighBias ("Accessory high decode bias", Vector) = (0,0,0,0)
        _CCProbeBase ("Base probe xy, inverse gain, bias", Vector) = (0,0,1,0)
        _CCProbeTrim ("Trim probe xy, inverse gain, bias", Vector) = (0,0,1,0)
        _CCProbeAccessory ("Accessory probe xy, inverse gain, bias", Vector) = (0,0,1,0)
'''

BODY = r'''    }

    SubShader
    {
        Tags { "Queue"="Transparent" "IgnoreProjector"="True" "RenderType"="Transparent" "PreviewType"="Plane"
               "CanUseSpriteAtlas"="True" }
        Cull Off
        Lighting Off
        ZWrite Off
        Blend One OneMinusSrcAlpha

        Pass
        {
            CGPROGRAM
            #pragma vertex vert
            #pragma fragment frag
            #pragma target 4.5
            #pragma shader_feature_local _ FLASHRIG_LAYERS_32 FLASHRIG_LAYERS_64 FLASHRIG_LAYERS_128
            #if defined(FLASHRIG_LAYERS_128)
                #define FLASHRIG_LAYER_LIMIT 128
            #elif defined(FLASHRIG_LAYERS_64)
                #define FLASHRIG_LAYER_LIMIT 64
            #elif defined(FLASHRIG_LAYERS_32)
                #define FLASHRIG_LAYER_LIMIT 32
            #else
                #define FLASHRIG_LAYER_LIMIT 16
            #endif
            #include "UnityCG.cginc"

            struct appdata { float4 vertex : POSITION; float4 color : COLOR; float2 uv : TEXCOORD0; };
            struct v2f { float4 pos : SV_POSITION; fixed4 color : COLOR; float2 uv : TEXCOORD0; };

            sampler2D _MainTex;
            sampler2D _CCConstantTex, _CCBaseTex, _CCTrimTex, _CCAccessoryTex;
            sampler2D _CCBaseHighTex, _CCTrimHighTex, _CCAccessoryHighTex;
            sampler2D _CCSkinTex, _CCHairTex, _CCEyeTex, _CCSkinHighTex, _CCHairHighTex, _CCEyeHighTex;
            float _CCExtraPalette;
            float4 _CCDirectSkin, _CCDirectHair, _CCDirectEye;
            float4 _CCSkinScale, _CCSkinBias, _CCHairScale, _CCHairBias, _CCEyeScale, _CCEyeBias;
            float4 _CCSkinHighScale, _CCSkinHighBias, _CCHairHighScale, _CCHairHighBias, _CCEyeHighScale, _CCEyeHighBias;
            float _CCEnabled, _CCKnot;
            float _CCDirectPalette;
            float4 _CCDirectBase, _CCDirectTrim, _CCDirectAccessory;
            float4 _CCConstantScale, _CCConstantBias, _CCBaseScale, _CCBaseBias;
            float4 _CCTrimScale, _CCTrimBias, _CCAccessoryScale, _CCAccessoryBias;
            float4 _CCBaseHighScale, _CCBaseHighBias, _CCTrimHighScale, _CCTrimHighBias, _CCAccessoryHighScale, _CCAccessoryHighBias;
            float4 _CCProbeBase, _CCProbeTrim, _CCProbeAccessory;
            float4 _AtlasSize;
            float4 _Tint;
            float _LayerCount;
            float _MorphFrame;
%(uniforms)s

            v2f vert(appdata v)
            {
                v2f o;
                o.pos = UnityObjectToClipPos(v.vertex);
                o.uv = v.uv;
                o.color = v.color;
                return o;
            }

            // Flash blend modes on straight colours (b = layers below, s = this layer)
            float3 FlashBlend(float3 b, float3 s, float mode)
            {
                if (mode < 3.5) return b * s;                                    // multiply
                if (mode < 4.5) return b + s - b * s;                            // screen
                if (mode < 5.5) return max(b, s);                                // lighten
                if (mode < 6.5) return min(b, s);                                // darken
                if (mode < 7.5) return abs(b - s);                               // difference
                if (mode < 8.5) return min(b + s, 1);                            // add
                if (mode < 9.5) return max(b - s, 0);                            // subtract
                float3 lo = 2 * b * s, hi = 1 - 2 * (1 - b) * (1 - s);
                if (mode < 13.5) return lerp(lo, hi, step(0.5, b));             // overlay
                return lerp(lo, hi, step(0.5, s));                               // hardlight
            }

            float4 Layer(float4 acc, float2 P, float2 dPx, float2 dPy, float4 rect, float4 A, float4 T, float4 CM,
                         float4 CA, float blendMode, float3 baseColor, float3 trimColor, float3 accessoryColor)
            {
                float2 q = float2(dot(A.xy, P) + T.x, dot(A.zw, P) + T.y);
                if (q.x < 0 || q.y < 0 || q.x > rect.z || q.y > rect.w) return acc;
                float2 uv = (rect.xy + clamp(q, 0.5, rect.zw - 0.5)) / _AtlasSize.xy;
                float2 gx = float2(dot(A.xy, dPx), dot(A.zw, dPx)) / _AtlasSize.xy;
                float2 gy = float2(dot(A.xy, dPy), dot(A.zw, dPy)) / _AtlasSize.xy;
                float4 s = tex2Dgrad(_MainTex, uv, gx, gy);
                [branch] if (_CCEnabled > 0.5)
                {
                    // Codex's opt-in reconstruction: fixed coefficient atlases + player-colour probes
                    float4 constant = tex2Dgrad(_CCConstantTex, uv, gx, gy);
                    float3 c = constant.rgb * _CCConstantScale.rgb + _CCConstantBias.rgb;
                    c += (tex2Dgrad(_CCBaseTex, uv, gx, gy).rgb * _CCBaseScale.rgb + _CCBaseBias.rgb) * min(baseColor, _CCKnot);
                    c += (tex2Dgrad(_CCTrimTex, uv, gx, gy).rgb * _CCTrimScale.rgb + _CCTrimBias.rgb) * min(trimColor, _CCKnot);
                    c += (tex2Dgrad(_CCAccessoryTex, uv, gx, gy).rgb * _CCAccessoryScale.rgb + _CCAccessoryBias.rgb) * min(accessoryColor, _CCKnot);
                    c += (tex2Dgrad(_CCBaseHighTex, uv, gx, gy).rgb * _CCBaseHighScale.rgb + _CCBaseHighBias.rgb) * max(baseColor - _CCKnot, 0);
                    c += (tex2Dgrad(_CCTrimHighTex, uv, gx, gy).rgb * _CCTrimHighScale.rgb + _CCTrimHighBias.rgb) * max(trimColor - _CCKnot, 0);
                    c += (tex2Dgrad(_CCAccessoryHighTex, uv, gx, gy).rgb * _CCAccessoryHighScale.rgb + _CCAccessoryHighBias.rgb) * max(accessoryColor - _CCKnot, 0);
                    [branch] if (_CCExtraPalette > 0.5)
                    {
                        c += (tex2Dgrad(_CCSkinTex, uv, gx, gy).rgb * _CCSkinScale.rgb + _CCSkinBias.rgb) * min(_CCDirectSkin.rgb, _CCKnot);
                        c += (tex2Dgrad(_CCHairTex, uv, gx, gy).rgb * _CCHairScale.rgb + _CCHairBias.rgb) * min(_CCDirectHair.rgb, _CCKnot);
                        c += (tex2Dgrad(_CCEyeTex, uv, gx, gy).rgb * _CCEyeScale.rgb + _CCEyeBias.rgb) * min(_CCDirectEye.rgb, _CCKnot);
                        c += (tex2Dgrad(_CCSkinHighTex, uv, gx, gy).rgb * _CCSkinHighScale.rgb + _CCSkinHighBias.rgb) * max(_CCDirectSkin.rgb - _CCKnot, 0);
                        c += (tex2Dgrad(_CCHairHighTex, uv, gx, gy).rgb * _CCHairHighScale.rgb + _CCHairHighBias.rgb) * max(_CCDirectHair.rgb - _CCKnot, 0);
                        c += (tex2Dgrad(_CCEyeHighTex, uv, gx, gy).rgb * _CCEyeHighScale.rgb + _CCEyeHighBias.rgb) * max(_CCDirectEye.rgb - _CCKnot, 0);
                    }
                    s = float4(c, constant.a);
                }
                float3 rgb = saturate(s.rgb * CM.rgb + CA.rgb);
                float a = saturate(s.a * CM.a + CA.a);
                if (blendMode > 0.5)
                {
                    // W3C compositing: where the layers below are transparent the source shows as normal
                    float3 cb = acc.a > 1e-4 ? acc.rgb / acc.a : 0;
                    rgb = lerp(rgb, saturate(FlashBlend(cb, rgb, blendMode)), acc.a);
                }
                return float4(rgb * a + acc.rgb * (1 - a), a + acc.a * (1 - a));
            }

            fixed4 frag(v2f i) : SV_Target
            {
                float2 P = i.uv * _AtlasSize.xy;
                float2 dPx = ddx(P), dPy = ddy(P);
                float3 baseColor = 0, trimColor = 0, accessoryColor = 0;
                [branch] if (_CCEnabled > 0.5)
                {
                    baseColor = saturate(tex2Dlod(_MainTex, float4(_CCProbeBase.xy / _AtlasSize.xy, 0, 0)).rgb * _CCProbeBase.z + _CCProbeBase.w);
                    trimColor = saturate(tex2Dlod(_MainTex, float4(_CCProbeTrim.xy / _AtlasSize.xy, 0, 0)).rgb * _CCProbeTrim.z + _CCProbeTrim.w);
                    accessoryColor = saturate(tex2Dlod(_MainTex, float4(_CCProbeAccessory.xy / _AtlasSize.xy, 0, 0)).rgb * _CCProbeAccessory.z + _CCProbeAccessory.w);
                }
                if (_CCDirectPalette > 0.5)
                {
                    baseColor = _CCDirectBase.rgb;
                    trimColor = _CCDirectTrim.rgb;
                    accessoryColor = _CCDirectAccessory.rgb;
                }
                float4 acc = 0, saved = 0;
%(calls)s
                acc.rgb *= _Tint.rgb;
                // SpriteRenderer colour, premultiplied like Sprites-Default
                acc.rgb *= i.color.rgb * i.color.a;
                acc.a *= i.color.a;
                return acc;
            }
            ENDCG
        }
    }
}
'''

props = []
for n in range(N):
    props += ['        _L%dRect ("L%d rect", Vector) = (0, 0, 0, 0)' % (n, n),
              '        _L%dA ("L%d A", Vector) = (1, 0, 0, 1)' % (n, n),
              '        _L%dT ("L%d T", Vector) = (0, 0, 0, 0)' % (n, n),
              '        _L%dCM ("L%d colour mult", Vector) = (1, 1, 1, 1)' % (n, n),
              '        _L%dCA ("L%d colour add", Vector) = (0, 0, 0, 0)' % (n, n),
              '        _L%dBlend ("L%d blend mode", Float) = 0' % (n, n),
              '        _L%dMorph ("L%d click state (-1 always)", Float) = -1' % (n, n),
              '        _L%dBegin ("L%d group begin", Float) = 0' % (n, n),
              '        _L%dEnd ("L%d group end blend", Float) = -1' % (n, n)]
uniforms = "\n".join("            float4 _L%dRect, _L%dA, _L%dT, _L%dCM, _L%dCA; float _L%dBlend, _L%dBegin, _L%dEnd, _L%dMorph;" % ((n,) * 9)
                     for n in range(N))
calls = "\n".join((('                #if FLASHRIG_LAYER_LIMIT > %d\n' % n) if n >= 16 else '') + '''                if (_LayerCount > %(i)d.5 && (_L%(i)dMorph < 0 || abs(_L%(i)dMorph - _MorphFrame) < 0.5))
                {
                    if (_L%(i)dBegin > 0.5) { saved = acc; acc = 0; }
                    acc = Layer(acc, P, dPx, dPy, _L%(i)dRect, _L%(i)dA, _L%(i)dT, _L%(i)dCM,
                                _L%(i)dCA, _L%(i)dBlend, baseColor, trimColor, accessoryColor);
                    if (_L%(i)dEnd >= 0)
                    {
                        float3 src = acc.a > 1e-6 ? acc.rgb / acc.a : 0;
                        float3 dst = saved.a > 1e-6 ? saved.rgb / saved.a : 0;
                        src = lerp(src, saturate(FlashBlend(dst, src, _L%(i)dEnd)), saved.a);
                        acc = float4(src * acc.a + saved.rgb * (1 - acc.a), acc.a + saved.a * (1 - acc.a));
                    }
                }''' % {'i': n} + ('\n                #endif' if n >= 16 else '') for n in range(N))
text = HEADER % {"n": N} + "\n".join(props) + "\n" + BODY % {"uniforms": uniforms, "calls": calls}
open(OUT, "w", encoding="utf-8", newline="\n").write(text)
print("wrote", OUT, N, "layers")
